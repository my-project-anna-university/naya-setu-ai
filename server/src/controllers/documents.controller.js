import LegalDocument from '../models/LegalDocument.js';
import {
  templateDefinitions,
  generateDocumentContent,
} from '../utils/documentTemplates.js';
import { getDbStatus } from '../config/db.js';

/**
 * @desc    Get all available legal document templates and required field definitions
 * @route   GET /api/documents/templates
 * @access  Public
 */
export const getTemplates = async (req, res, next) => {
  try {
    return res.status(200).json({
      success: true,
      count: templateDefinitions.length,
      templates: templateDefinitions,
    });
  } catch (error) {
    next(error);
  }
};

/**
 * @desc    Generate a legal document (RTI, Legal Notice, Consumer Complaint, Affidavit)
 * @route   POST /api/documents/generate
 * @access  Public (Optional User Auth)
 */
export const generateDocument = async (req, res, next) => {
  try {
    const { type, data, title } = req.body;

    if (!type) {
      return res.status(400).json({
        success: false,
        message: 'Document type is required (rti, notice, complaint, affidavit).',
      });
    }

    if (!data || typeof data !== 'object') {
      return res.status(400).json({
        success: false,
        message: 'Form data object is required to populate template.',
      });
    }

    const generated = generateDocumentContent(type, data);
    const finalTitle = title || generated.title;

    let savedDoc = null;

    // Save to database if connected
    if (getDbStatus()) {
      try {
        const userId = req.user?.id || req.user?._id || data.userId || null;
        savedDoc = await LegalDocument.create({
          userId,
          type: type.toLowerCase(),
          title: finalTitle,
          content: generated.content,
          metadata: {
            ...data,
            generatedAt: new Date(),
          },
          status: 'completed',
        });
      } catch (dbErr) {
        console.warn('[Documents Controller] Could not persist document to DB:', dbErr.message);
      }
    }

    return res.status(201).json({
      success: true,
      message: 'Legal document generated successfully.',
      document: {
        id: savedDoc ? savedDoc._id : `temp_${Date.now()}`,
        type: type.toLowerCase(),
        title: finalTitle,
        content: generated.content,
        metadata: data,
        createdAt: new Date(),
      },
    });
  } catch (error) {
    next(error);
  }
};

/**
 * @desc    Get all documents generated by a specific user
 * @route   GET /api/documents/user/:userId
 * @access  Private / Public
 */
export const getUserDocuments = async (req, res, next) => {
  try {
    const { userId } = req.params;

    if (getDbStatus()) {
      const documents = await LegalDocument.find({ userId })
        .sort({ createdAt: -1 })
        .select('-metadata');

      return res.status(200).json({
        success: true,
        count: documents.length,
        documents,
      });
    }

    return res.status(200).json({
      success: true,
      count: 0,
      documents: [],
      message: 'Database storage inactive. Operating in ephemeral mode.',
    });
  } catch (error) {
    next(error);
  }
};

/**
 * @desc    Get a single document by ID
 * @route   GET /api/documents/:id
 * @access  Public
 */
export const getDocumentById = async (req, res, next) => {
  try {
    const { id } = req.params;

    if (getDbStatus()) {
      const document = await LegalDocument.findById(id);
      if (!document) {
        return res.status(404).json({
          success: false,
          message: 'Document not found.',
        });
      }

      return res.status(200).json({
        success: true,
        document,
      });
    }

    return res.status(404).json({
      success: false,
      message: 'Database not connected to retrieve stored documents.',
    });
  } catch (error) {
    next(error);
  }
};

export default {
  getTemplates,
  generateDocument,
  getUserDocuments,
  getDocumentById,
};
